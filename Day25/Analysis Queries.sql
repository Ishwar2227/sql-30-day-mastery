```
Q1. Executive Summary: Total revenue, total customers,
    total orders, ARPU, repeat purchase rate. Single row.

Q2. Revenue by state with growth: State, revenue,
    pct_of_total, rank by revenue.

Q3. Top 5 products by profit margin with their
    category ranking.

Q4. Customer cohort analysis: Cohort month,
    cohort size, revenue in months 0, 1, 2 after acquisition.

Q5. Churn risk report: All customers with
    churn_risk = 'High'. Show days inactive,
    last order, total lifetime value.

Q6. Market basket: Top 10 product pairs
    bought together. Show pair and frequency.
